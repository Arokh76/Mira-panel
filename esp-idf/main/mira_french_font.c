/* LVGL 9.6 native font callbacks. The original Mira beta glyph bitmaps and
 * advance widths above are retained byte for byte. No Arduino dependency.
 * Font glyph data is only 4bpp alpha; fallback handles ordinary ASCII. */
static const MiraGlyph *fr_find(const MiraFontSpec *spec,uint32_t code){
    int lo=0,hi=(int)spec->glyph_count-1;
    while(lo<=hi){
        int mid=(lo+hi)/2;
        uint32_t c=spec->glyphs[mid].code;
        if(c==code)return &spec->glyphs[mid];
        if(c<code)lo=mid+1;
        else hi=mid-1;
    }
    return NULL;
}
static bool fr_glyph_dsc(const lv_font_t *font,lv_font_glyph_dsc_t *out,
                         uint32_t letter,uint32_t next){
    (void)next;
    const MiraFontSpec *spec=(const MiraFontSpec *)font->dsc;
    const MiraGlyph *g=fr_find(spec,letter);
    if(!g)return false;
    out->resolved_font=font;
    out->gid.index=(uint32_t)(g-spec->glyphs)+1u;
    out->format=LV_FONT_GLYPH_FORMAT_A4;
    out->adv_w=(g->adv_w+8u)>>4; // beta stores 1/16 pixel advances
    out->box_w=g->box_w;
    out->box_h=g->box_h;
    out->ofs_x=g->ofs_x;
    out->ofs_y=g->ofs_y;
    out->stride=0; // continuous nibble-packed rows
    out->is_placeholder=0;
    return true;
}
static const void *fr_glyph_bitmap(lv_font_glyph_dsc_t *glyph,
                                   lv_draw_buf_t *draw_buf){
    if(!glyph||!glyph->resolved_font||!glyph->gid.index)return NULL;
    const MiraFontSpec *spec=(const MiraFontSpec *)glyph->resolved_font->dsc;
    uint32_t id=glyph->gid.index-1;
    if(id>=spec->glyph_count)return NULL;
    const MiraGlyph *g=&spec->glyphs[id];
    const uint8_t *packed=spec->bitmap+g->bitmap_index;
    if(glyph->req_raw_bitmap)return packed;
    if(!draw_buf||!draw_buf->data)return NULL;
    uint8_t *out=(uint8_t *)draw_buf->data;
    uint32_t stride=lv_draw_buf_width_to_stride(g->box_w,LV_COLOR_FORMAT_A8);
    for(uint32_t y=0;y<g->box_h;y++){
        for(uint32_t x=0;x<g->box_w;x++){
            uint32_t index=y*(uint32_t)g->box_w+x;
            uint8_t pair=packed[index>>1];
            uint8_t nibble=(index&1u)?(pair&0x0fu):(pair>>4);
            out[y*stride+x]=(uint8_t)(nibble*17u);
        }
    }
    lv_draw_buf_flush_cache(draw_buf,NULL);
    return draw_buf;
}
