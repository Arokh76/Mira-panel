static const MiraGlyph* findGlyph(const MiraFontSpec* spec, uint32_t code) {
  int lo = 0;
  int hi = (int)spec->glyph_count - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2;
    uint32_t c = spec->glyphs[mid].code;
    if (c == code) return &spec->glyphs[mid];
    if (c < code) lo = mid + 1;
    else hi = mid - 1;
  }
  return nullptr;
}

static bool fr_get_glyph_dsc(const lv_font_t* font, lv_font_glyph_dsc_t* dsc, uint32_t letter, uint32_t letter_next) {
  (void)letter_next;
  const MiraFontSpec* spec = static_cast<const MiraFontSpec*>(font->dsc);
  const MiraGlyph* g = findGlyph(spec, letter);
  if (!g) return false;
  dsc->resolved_font = font;
  // IMPORTANT : les tables generees stockent adv_w en 1/16 de pixel,
  // comme lv_font_fmt_txt_glyph_dsc_t. Mais un callback get_glyph_dsc
  // personnalise doit renvoyer une largeur EN PIXELS. Sans cette conversion,
  // un caractere accentue (e, a, etc.) reserve ~140 px et ecarte/coupe tout
  // le texte autour. C'etait la cause des "Parame    tres", "rature", etc.
  dsc->adv_w = (g->adv_w + 8) >> 4;
  dsc->box_w = g->box_w;
  dsc->box_h = g->box_h;
  dsc->ofs_x = g->ofs_x;
  dsc->ofs_y = g->ofs_y;
  dsc->bpp = 4;
  dsc->is_placeholder = 0;
  return true;
}

static const uint8_t* fr_get_glyph_bitmap(const lv_font_t* font, uint32_t letter) {
  const MiraFontSpec* spec = static_cast<const MiraFontSpec*>(font->dsc);
  const MiraGlyph* g = findGlyph(spec, letter);
  return g ? spec->bitmap + g->bitmap_index : nullptr;
}


